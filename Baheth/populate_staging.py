def main():
    os.chdir(HERE)
    proc = subprocess.Popen(
        [PYTHON, "-m", "uvicorn", "main:app", "--host", "127.0.0.1", "--port", "8000"],
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
    )

    for _ in range(30):
        try:
            urllib.request.urlopen("http://127.0.0.1:8000/docs", timeout=2)
            break
        except Exception:
            time.sleep(0.5)
    else:
        out = proc.communicate(timeout=2)[0].decode("utf-8", errors="replace")
        print("Server failed to start. Output:")
        print(out)
        proc.kill()
        sys.exit(1)

    print("Server started on http://127.0.0.1:8000")

    payload = {"shards": SHARDS}
    body = json.dumps(payload, ensure_ascii=False).encode("utf-8")

    req = urllib.request.Request(
        "http://127.0.0.1:8000/index-shards",
        data=body,
        headers={"Content-Type": "application/json"},
        method="POST",
    )

    try:
        resp = urllib.request.urlopen(req, timeout=30)
        result = json.loads(resp.read())
    except urllib.error.HTTPError as e:
        print(f"HTTP {e.code}: {e.reason}", file=sys.stderr)
        print("Response body:", e.read().decode("utf-8", errors="replace"), file=sys.stderr)
        proc.kill()
        sys.exit(1)

    report = []
    report.append(f"Status:       {result['status']}")
    report.append(f"Indexed:      {result['indexed_count']} shards")
    report.append(f"IDs created:  {result['ids'][0]} .. {result['ids'][-1]}")

    categories = {
        "Heavy diacritics": SHARDS[0]["text"],
        "Alef mutations": SHARDS[7]["text"],
        "Embedded HTML": SHARDS[16]["text"],
    }
    for label, sample in categories.items():
        report.append(f"\n  [{label}]")
        report.append(f"  {sample[:120]}...")

    proc.terminate()
    proc.wait(timeout=5)
    report.append(f"\nSUCCESS: {result['indexed_count']} shards ingested. Server stopped.")

    out_path = os.path.join(HERE, "ingestion_report.txt")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(report))
    print(f"Report written to: {out_path}")


if __name__ == "__main__":
    main()
